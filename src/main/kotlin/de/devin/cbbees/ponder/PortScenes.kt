object PortScenes {

    private fun CreateSceneBuilder.portState(pos: BlockPos, state: PortState) =
        world().modifyBlock(pos, { it.setValue(PortBlock.PORT_STATE, state) as BlockState }, false)

    private fun CreateSceneBuilder.portType(pos: BlockPos, type: PortType) =
        world().modifyBlock(pos, { it.setValue(PortBlock.PORT_TYPE, type) as BlockState }, false)

    private fun CreateSceneBuilder.cargoMode(pos: BlockPos, mode: TransportMode) =
        world().modifyBlock(pos, { it.setValue(TransportPortBlock.TRANSPORT_MODE, mode) as BlockState }, false)

    private fun CreateSceneBuilder.tank(pos: BlockPos, change: (FluidTankBlockEntity) -> Unit) =
        world().modifyBlockEntity(pos, FluidTankBlockEntity::class.java) { change(it) }

    private fun CreateSceneBuilder.wrench(util: SceneBuildingUtil, pos: BlockPos, ticks: Int = 60) =
        overlay().showControls(util.vector().blockSurface(pos, Direction.UP), Pointing.DOWN, ticks)
            .withItem(CreateItems.WRENCH.asStack())
            .rightClick()

    fun logisticsPort(builder: SceneBuilder, util: SceneBuildingUtil) {
        val scene = CreateSceneBuilder(builder)
        scene.title("logistics_port", "The Logistics Port")
        scene.configureBasePlate(0, 0, 7)
        scene.showBasePlate()
        scene.idle(10)

        val hive = util.grid().at(5, 1, 5)
        val vault = util.grid().at(1, 1, 3)
        val port = util.grid().at(1, 2, 3)
        val storage = util.grid().at(1, 1, 5)
        val storagePort = util.grid().at(1, 2, 5)
        val siteFrom = util.grid().at(2, 1, 0)
        val siteTo = util.grid().at(4, 1, 0)
        val siteCenter = util.vector().centerOf(util.grid().at(3, 1, 0))
        val spawn = PonderBees.above(util, hive, 1.5)

        PonderBees.showPoweredHive(scene, util, hive, util.grid().at(6, 1, 5))
        scene.idle(10)
        PonderEffects.highlight(scene, PonderPalette.WHITE, siteFrom, siteTo, 80)
        scene.overlay().showText(80)
            .text("Bees need the materials for every block they place")
            .placeNearTarget()
            .pointAt(siteCenter)
        scene.idle(90)

        scene.world().showSection(util.select().position(vault), Direction.DOWN)
        scene.idle(10)
        val bee = PonderBees.createBee(scene, BeeType.CONSTRUCTION, spawn)
        val atVault = PonderBees.above(util, vault, 0.9)
        PonderBees.fly(scene, bee, spawn, atVault, 35)
        PonderEffects.highlight(scene, PonderPalette.RED, vault, vault, 70)
        scene.overlay().showText(70)
            .text("But they can't take anything out of an inventory on their own")
            .colored(PonderPalette.RED)
            .placeNearTarget()
            .pointAt(util.vector().blockSurface(vault, Direction.WEST))
        scene.idle(75)
        PonderBees.fly(scene, bee, atVault, spawn, 30)
        PonderBees.hide(scene, listOf(bee))
        scene.idle(10)

        scene.world().showSection(util.select().position(port), Direction.DOWN)
        scene.idle(15)
        scene.overlay().showOutlineWithText(util.select().fromTo(vault, port), 90)
            .text("A Logistics Port lets bees take items from the inventory it sits on")
            .attachKeyFrame()
            .placeNearTarget()
            .pointAt(util.vector().blockSurface(port, Direction.WEST))
        scene.idle(100)

        scene.overlay().showCenteredScrollInput(port, Direction.UP, 70)
        scene.overlay().showText(70)
            .text("If several ports offer an item, the one with the highest priority is used first")
            .placeNearTarget()
            .pointAt(util.vector().blockSurface(port, Direction.UP))
        scene.idle(80)

        val worker = PonderBees.createBee(scene, BeeType.CONSTRUCTION, spawn)
        val atPort = PonderBees.above(util, port, 0.5)
        val atSite = PonderBees.above(util, util.grid().at(3, 1, 0))
        scene.portState(port, PortState.BUSY)
        PonderBees.fly(scene, worker, spawn, atPort, 35)
        PonderEffects.signal(scene, util, port)
        PonderBees.carry(scene, worker, ItemStack(Items.OAK_PLANKS))
        scene.idle(10)
        scene.portState(port, PortState.VALID)
        scene.overlay().showText(70)
            .text("Now bees pick up the items they need and get to work")
            .colored(PonderPalette.GREEN)
            .placeNearTarget()
            .pointAt(siteCenter)
        PonderBees.fly(scene, worker, atPort, atSite, 35)
        PonderBees.carry(scene, worker, ItemStack.EMPTY)
        scene.world().showSection(util.select().fromTo(siteFrom, siteTo), Direction.DOWN)
        for (x in 2..4) PonderEffects.sparkle(scene, util, util.grid().at(x, 1, 0))
        scene.idle(40)

        scene.world().showSection(util.select().position(storage), Direction.DOWN)
        scene.idle(5)
        scene.world().showSection(util.select().position(storagePort), Direction.DOWN)
        scene.idle(10)
        scene.wrench(util, storagePort)
        scene.idle(10)
        scene.portType(storagePort, PortType.INSERT)
        scene.overlay().showOutlineWithText(util.select().fromTo(storage, storagePort), 90)
            .text("Switched to INSERT with a wrench, a port stores what bees bring back, like blocks from a deconstruction")
            .attachKeyFrame()
            .colored(PonderPalette.BLUE)
            .placeNearTarget()
            .pointAt(util.vector().blockSurface(storagePort, Direction.WEST))
        val atStorage = PonderBees.above(util, storagePort, 0.5)
        PonderBees.carry(scene, worker, ItemStack(Items.COBBLESTONE))
        PonderBees.fly(scene, worker, atSite, atStorage, 40)
        PonderEffects.signal(scene, util, storagePort)
        PonderBees.carry(scene, worker, ItemStack.EMPTY)
        scene.idle(20)
        PonderBees.fly(scene, worker, atStorage, spawn, 35)
        PonderBees.hide(scene, listOf(worker))
        scene.idle(30)
        scene.markAsFinished()
    }


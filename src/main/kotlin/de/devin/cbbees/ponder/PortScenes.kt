            scene.world().showIndependentSection(util.select().position(link), Direction.DOWN)
        scene.idle(15)
        PonderEffects.highlight(scene, PonderPalette.WHITE, siteFrom, siteTo, 90)
        scene.overlay().showText(90)
            .text("Bees build with what their network holds, while your Create logistics network may hold much more")
            .placeNearTarget()
            .pointAt(util.vector().blockSurface(packager, Direction.WEST))
        scene.idle(100)

        val waiting = PonderBees.createBee(scene, BeeType.CONSTRUCTION, spawn)
        PonderBees.fly(scene, waiting, spawn, siteCenter.add(0.0, 1.0, 0.0), 30)
        PonderEffects.highlight(scene, PonderPalette.RED, siteFrom, siteTo, 80)
        scene.overlay().showText(80)
            .text("When a job is missing materials, the bees can only wait")
            .colored(PonderPalette.RED)
            .placeNearTarget()
            .pointAt(siteCenter)
        scene.idle(85)
        PonderBees.fly(scene, waiting, siteCenter.add(0.0, 1.0, 0.0), spawn, 30)
        PonderBees.hide(scene, listOf(waiting))
        scene.idle(10)

        scene.world().moveSection(linkSection, util.vector().of(0.0, 0.25, 0.0), 8)
        scene.overlay().showControls(util.vector().topOf(link), Pointing.DOWN, 50)
            .rightClick()
            .withItem(AllBlocks.WAGGLE_PORT.asStack())

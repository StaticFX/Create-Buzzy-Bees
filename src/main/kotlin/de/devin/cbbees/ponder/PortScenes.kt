        val atFarm = PonderBees.above(util, farmPort, 0.5)
        val atStore = PonderBees.above(util, storePort, 0.5)
        scene.overlay().showText(90)
            .text("Mechanical Bumble Bees pick up new items from the Provider and deliver them to the Requester")
            .attachKeyFrame()
            .colored(PonderPalette.GREEN)
            .placeNearTarget()
            .pointAt(util.vector().blockSurface(hive, Direction.UP))
        scene.portState(farmPort, PortState.BUSY)
        PonderBees.fly(scene, bee, spawn, atFarm, 35)
        PonderEffects.signal(scene, util, farmPort)
        PonderBees.carry(scene, bee, wheat)
        scene.portState(farmPort, PortState.VALID)

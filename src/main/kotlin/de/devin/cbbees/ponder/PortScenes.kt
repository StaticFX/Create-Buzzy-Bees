        scene.idle(5)
        scene.world().showSection(util.select().position(overflowPort), Direction.DOWN)
        scene.idle(10)
        scene.overlay().showLine(PonderPalette.GREEN, util.vector().centerOf(farmPort), util.vector().centerOf(overflowPort), 90)
        scene.overlay().showCenteredScrollInput(storePort, Direction.UP, 90)
        scene.overlay().showText(90)
            .text("With several Requesters on a frequency, the one with the highest priority is served first, not the closest")
            .attachKeyFrame()
            .placeNearTarget()
            .pointAt(util.vector().blockSurface(storePort, Direction.UP))
        scene.idle(100)

        PonderEffects.highlight(scene, PonderPalette.RED, store, store, 140)
        PonderBees.fly(scene, bee, atStore, atFarm, 40)
        PonderBees.carry(scene, bee, wheat)
        PonderBees.fly(scene, bee, atFarm, atStore, 45)
        PonderBees.carry(scene, bee, ItemStack.EMPTY)
        val dropAt = util.vector().blockSurface(store, Direction.WEST).add(-0.4, 0.2, 0.0)
        val spilled = (0..2).map { i ->
            scene.world().createItemEntity(dropAt.add(0.0, 0.0, i * 0.3 - 0.3), Vec3(-0.05, 0.15, (i - 1) * 0.03), ItemStack(Items.WHEAT, 16))
        }
        scene.overlay().showText(130)
            .text("Bumble Bees deliver everything they carry. If the destination runs out of space, the leftover items are dropped next to it")
            .colored(PonderPalette.RED)
            .placeNearTarget()
            .pointAt(dropAt)
        scene.idle(140)
        spilled.forEach { scene.world().modifyEntity(it) { entity -> entity.discard() } }
        PonderBees.fly(scene, bee, atStore, spawn, 40)
        PonderBees.hide(scene, listOf(bee))
        scene.idle(20)
        scene.markAsFinished()
    }

    fun dockPort(builder: SceneBuilder, util: SceneBuildingUtil) {
        val scene = CreateSceneBuilder(builder)
        scene.title("dock_port", "The Dock Port")
        scene.configureBasePlate(0, 0, 7)
        scene.showBasePlate()
        scene.idle(10)

        val hive = util.grid().at(5, 1, 5)
        val tank = util.grid().at(1, 1, 3)
        val dock = util.grid().at(1, 2, 3)
        val storageTank = util.grid().at(1, 1, 5)
        val storageDock = util.grid().at(1, 2, 5)
        val water = util.grid().at(3, 1, 1)
        val basin = util.select().fromTo(2, 1, 0, 4, 1, 2).substract(util.select().position(water))
        val spawn = PonderBees.above(util, hive, 1.5)

        PonderBees.showPoweredHive(scene, util, hive, util.grid().at(6, 1, 5))
        scene.world().showSection(basin, Direction.DOWN)
        scene.idle(15)
        PonderEffects.highlight(scene, PonderPalette.WHITE, water, water, 80)
        scene.overlay().showText(80)
            .text("Some builds need fluids, like the water in this fountain")
            .placeNearTarget()
            .pointAt(util.vector().centerOf(water))
        scene.idle(90)

        scene.tank(tank) { it.tankInventory.fill(FluidStack(Fluids.WATER, 8000), FluidAction.EXECUTE) }
        scene.world().showSection(util.select().position(tank), Direction.DOWN)
        scene.idle(15)
        PonderEffects.highlight(scene, PonderPalette.RED, tank, tank, 70)
        scene.overlay().showText(70)
            .text("Bees can't drain a tank on their own")
            .colored(PonderPalette.RED)
            .placeNearTarget()
            .pointAt(util.vector().blockSurface(tank, Direction.WEST))
        scene.idle(80)

        scene.world().showSection(util.select().position(dock), Direction.DOWN)
        scene.idle(15)
        scene.overlay().showOutlineWithText(util.select().fromTo(tank, dock), 80)
            .text("A Dock Port lets bees take fluids from the tank it sits on")
            .attachKeyFrame()
            .placeNearTarget()
            .pointAt(util.vector().blockSurface(dock, Direction.WEST))
        scene.idle(90)

        val bee = PonderBees.createBee(scene, BeeType.CONSTRUCTION, spawn)
        val atDock = PonderBees.above(util, dock, 0.5)
        val atWater = PonderBees.above(util, water, 0.8)
        scene.portState(dock, PortState.BUSY)
        PonderBees.fly(scene, bee, spawn, atDock, 35)
        scene.tank(tank) { it.tankInventory.drain(1000, FluidAction.EXECUTE) }
        PonderEffects.splash(scene, util, dock)
        PonderBees.carry(scene, bee, ItemStack(Items.WATER_BUCKET))
        scene.idle(10)
        scene.portState(dock, PortState.VALID)
        scene.overlay().showText(70)
            .text("Bees carry the fluid over and place it")
            .colored(PonderPalette.GREEN)
            .placeNearTarget()
            .pointAt(util.vector().centerOf(water))
        PonderBees.fly(scene, bee, atDock, atWater, 35)
        PonderBees.carry(scene, bee, ItemStack.EMPTY)
        scene.world().showSection(util.select().position(water), Direction.DOWN)
        PonderEffects.splash(scene, util, water)
        PonderEffects.highlight(scene, PonderPalette.GREEN, water, water, 50)
        scene.idle(40)

        scene.world().showSection(util.select().position(storageTank), Direction.DOWN)
        scene.idle(5)
        scene.world().showSection(util.select().position(storageDock), Direction.DOWN)
        scene.idle(10)
        scene.wrench(util, storageDock)
        scene.idle(10)
        scene.portType(storageDock, PortType.INSERT)
        scene.overlay().showOutlineWithText(util.select().fromTo(storageTank, storageDock), 90)
            .text("Switched to INSERT with a wrench, a Dock Port stores fluids bees bring back")
            .attachKeyFrame()
            .colored(PonderPalette.BLUE)
            .placeNearTarget()
            .pointAt(util.vector().blockSurface(storageDock, Direction.WEST))
        val atStorage = PonderBees.above(util, storageDock, 0.5)
        PonderBees.carry(scene, bee, ItemStack(Items.WATER_BUCKET))
        PonderBees.fly(scene, bee, atWater, atStorage, 35)
        scene.tank(storageTank) { it.tankInventory.fill(FluidStack(Fluids.WATER, 1000), FluidAction.EXECUTE) }
        PonderEffects.splash(scene, util, storageDock)
        PonderBees.carry(scene, bee, ItemStack.EMPTY)
        scene.idle(20)
        PonderBees.fly(scene, bee, atStorage, spawn, 35)
        PonderBees.hide(scene, listOf(bee))
        scene.idle(30)
        scene.markAsFinished()
    }

    fun wagglePort(builder: SceneBuilder, util: SceneBuildingUtil) {
